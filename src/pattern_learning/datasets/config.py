from __future__ import annotations

from pathlib import Path

from pydantic import BaseModel, ConfigDict, Field, model_validator

from config_loading import load_yaml_config
from generation import ACTIVE_ENVS
from paths import get_artifact_layout


DATASET_CONFIG_VERSION = "1"


class DatasetSplitConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    name: str
    sample_count: int = Field(gt=0)
    sample_offset: int = Field(ge=0)


class DatasetBuildConfig(BaseModel):
    model_config = ConfigDict(extra="forbid")

    config_version: str = DATASET_CONFIG_VERSION
    dataset_name: str
    env_ids: list[str]
    splits: list[DatasetSplitConfig]
    notes: list[str] = Field(default_factory=list)

    @model_validator(mode="after")
    def validate_dataset_scope(self) -> "DatasetBuildConfig":
        allowed_envs = set(ACTIVE_ENVS)
        unknown_envs = sorted(set(self.env_ids) - allowed_envs)
        if unknown_envs:
            raise ValueError(
                "dataset config includes unsupported env_ids: " + ", ".join(unknown_envs)
            )
        if not self.env_ids:
            raise ValueError("dataset config must include at least one env_id")
        if len(self.env_ids) != len(set(self.env_ids)):
            raise ValueError("dataset config env_ids must be unique")

        split_names = [split.name for split in self.splits]
        if len(split_names) != len(set(split_names)):
            raise ValueError("dataset config split names must be unique")
        return self


def default_dataset_config_path() -> Path:
    return get_artifact_layout().config_root / "datasets" / "default.yaml"


def load_dataset_build_config(path: Path) -> DatasetBuildConfig:
    data = load_yaml_config(path)
    return DatasetBuildConfig.model_validate(data)


def build_legacy_random_dataset_config(
    *,
    train_count: int = 1000,
    test_count: int = 100,
    env_ids: list[str] | None = None,
) -> DatasetBuildConfig:
    return DatasetBuildConfig(
        config_version=DATASET_CONFIG_VERSION,
        dataset_name="random_trace_dataset",
        env_ids=list(env_ids or ACTIVE_ENVS),
        splits=[
            DatasetSplitConfig(name="train", sample_count=train_count, sample_offset=0),
            DatasetSplitConfig(name="test", sample_count=test_count, sample_offset=1_000_003),
        ],
        notes=["Legacy compatibility config generated by dataset.build_random_trace_dataset"],
    )
